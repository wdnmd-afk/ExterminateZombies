import assert from 'node:assert/strict';
import { setTimeout as sleep } from 'node:timers/promises';
import { startAcceptanceSession, snapshotExpression } from './cdp-acceptance-session.mjs';

const session = await startAcceptanceSession(process.argv[2] ?? 'frenzy-boundary-r01', Number(process.argv[3] ?? 9345));
const { browser, save } = session;
const results = [];
const inspect = () => browser.evaluate(snapshotExpression);
const waitScene = async name => { await browser.wait(`window.__GAME__?.scene.isActive(${JSON.stringify(name)})`, name, 60000); await sleep(180); };
const saves = () => browser.evaluate("(() => { const { SaveManager, SAVE_KEYS } = window.__ACCEPTANCE__; return { levels: SaveManager.load(SAVE_KEYS.unlockedLevels, []), weapons: SaveManager.getUnlockedWeapons(), loadout: SaveManager.getWeaponLoadout(), character: SaveManager.getPreferredCharacterId(), starter: SaveManager.getPreferredStarterWeapon(), records: SaveManager.load(SAVE_KEYS.frenzyRecords, {}) }; })()");
const park = (x, y) => browser.evaluate(`window.__FRENZY_FIXTURE__.parkPlayer(${x}, ${y})`);
const stateCondition = condition => `(() => { const scene = window.__GAME__.scene.getScene('GameScene'); const state = scene.getState(); return ${condition}; })()`;
const fireUntil = async (condition, label) => {
  const deadline = Date.now() + 10000;
  while (Date.now() < deadline && !await browser.evaluate(condition)) {
    await browser.fire(true); await sleep(90); await browser.fire(false); await sleep(180);
  }
  assert.equal(await browser.evaluate(condition), true, label);
};
const targetDown = async id => {
  const point = await browser.evaluate(`window.__FRENZY_FIXTURE__.prepareTarget(${JSON.stringify(id)})`);
  await browser.move('GameScene', point.x, point.y);
  await fireUntil(stateCondition(`state.frenzy.targets[${JSON.stringify(id)}] === 'dropped'`), `${id} dropped`);
  const dropped = await inspect();
  await save(`${id}-dropped.json`, dropped);
  assert.equal(dropped.state.frenzy.targets[id], 'dropped');
  assert.ok(Math.hypot(dropped.diagnostics.player.x - point.x, dropped.diagnostics.player.y - point.y) > 46);
  return dropped.cores.find(core => Math.hypot(core.x - point.x, core.y - point.y) < 80);
};
const collect = async (id, core) => {
  assert.ok(core, `No visible ${id} core`);
  await park(core.x, core.y + 72);
  await browser.key('KeyW', true);
  await browser.wait(stateCondition(`state.frenzy.targets[${JSON.stringify(id)}] === 'collected'`), `${id} collected`, 5000);
  await browser.key('KeyW', false);
  await sleep(80);
  const snapshot = await inspect();
  await save(`${id}-collected.json`, snapshot);
  await browser.screenshot(`${id}-collected`);
  return snapshot;
};
const layout = async (name, width, height) => {
  await browser.send('Emulation.setDeviceMetricsOverride', { width, height, deviceScaleFactor: 1, mobile: false });
  await sleep(450);
  const snapshot = await inspect();
  const texts = await browser.texts('HUDScene');
  const display = await browser.evaluate("(async () => (await import('/src/systems/DisplayManager.ts')).getRuntimeDisplayLayout())()");
  await save(`${name}.json`, { snapshot, texts, display });
  await browser.screenshot(name);
  return { snapshot, texts, display };
};

try {
  await save('fixture-scope.json', { scope: '真实菜单/生产 GameScene/真实射击与核心靠近拾取；将自然目标移位、冻结、削至1HP，其余敌人隔离。所有受控局 recordEligible=false。不是自然通关、TTK、难度或真实成绩。超时仅压缩最后一秒之前等待。' });
  const baseline = await saves();
  await browser.clickText('MainMenuScene', '狂潮挑战'); await waitScene('FrenzyPreparationScene');
  await browser.tap('Digit3'); await browser.tap('Enter'); await waitScene('GameScene');
  const initial = await inspect();
  await browser.evaluate("(async () => { const { attachFrenzyFixture } = await import('/scripts/cdp-frenzy-fixture.mjs'); return attachFrenzyFixture(window.__GAME__); })()");
  await park(640, 430);
  await browser.tap('Digit1'); await browser.move('GameScene', 1150, 430);
  await browser.fire(true); await sleep(620); await browser.fire(false);
  const backupBefore = await inspect();
  await browser.tap('Digit2');
  const ammoCore = await targetDown('ammo');
  let reload = await inspect();
  if (!reload.reloading) { await browser.tap('KeyR'); reload = await inspect(); }
  assert.equal(reload.reloading, true, 'Ammo core must be picked during real reload');
  await save('ammo-before-reload-pickup.json', reload);
  const ammo = await collect('ammo', ammoCore);
  assert.equal(ammo.reloading, false);
  const ammoStock = ammo.state.player.reserve;
  await sleep(2200);
  const settled = await inspect();
  assert.deepEqual(settled.state.player.reserve, ammoStock);
  assert.equal(settled.state.player.magazines.rpg, ammo.state.player.magazines.rpg);
  await browser.tap('Digit1');
  const switched = await inspect();
  assert.equal(switched.state.player.magazines.pistol, backupBefore.state.player.magazines.pistol);
  await browser.tap('Digit2'); await park(640, 430); await browser.move('GameScene', 1150, 430);
  const freeBefore = await inspect();
  await browser.fire(true); await sleep(950); await browser.fire(false);
  const freeAfter = await inspect();
  const freeFrames = await browser.evaluate(`window.__FRENZY_FIXTURE__.frames.filter(frame => frame.frame > ${freeBefore.frame} && frame.frame <= ${freeAfter.frame})`);
  assert.ok(freeFrames.some(frame => frame.bullets.length > 0), 'Free-ammo test requires a real emitted projectile');
  assert.equal(freeAfter.state.player.magazines.rpg, freeBefore.state.player.magazines.rpg);
  assert.deepEqual(freeAfter.state.player.reserve, freeBefore.state.player.reserve);
  await save('ammo-reload-switch-free.json', { backupBefore, reload, ammo, settled, switched, freeBefore, freeAfter });
  const breachCore = await targetDown('breach');
  const breach = await collect('breach', breachCore);
  assert.ok(breach.state.frenzy.ammoUntilMs > breach.state.frenzy.elapsedMs);
  assert.ok(breach.state.frenzy.breachUntilMs > breach.state.frenzy.elapsedMs);
  const wide = await layout('double-reward-wide', 1920, 720);
  const narrow = await layout('double-reward-narrow', 960, 720);
  for (const sample of [wide, narrow]) {
    const compact = sample.display.hudSidebarTier === 'compact';
    assert.ok(sample.texts.some(entry => compact ? /^弹\d+s\s+伤\d+s$/.test(entry.text) : entry.text.includes('弹匣免耗 ') && entry.text.includes('火力 ×1.5')));
    assert.ok(sample.snapshot.state.frenzy.ammoUntilMs > sample.snapshot.state.frenzy.elapsedMs);
  }
  await browser.tap('Escape');
  const paused = await inspect();
  await sleep(30000);
  await browser.tap('Escape'); await sleep(100);
  const resumed = await inspect();
  assert.ok(resumed.state.frenzy.elapsedMs - paused.state.frenzy.elapsedMs < 1000);
  assert.equal(resumed.state.frenzy.ammoUntilMs, paused.state.frenzy.ammoUntilMs);
  assert.equal(resumed.state.frenzy.breachUntilMs, paused.state.frenzy.breachUntilMs);
  await save('dual-reward-pause.json', { paused, resumed });
  await park(640, 430);
  await browser.wait(stateCondition('state.frenzy.elapsedMs >= state.frenzy.ammoUntilMs'), 'ammo reward naturally expired', 20000);
  await browser.move('GameScene', 1150, 430);
  const expiredBefore = await inspect();
  await browser.fire(true); await sleep(130); await browser.fire(false);
  const expiredAfter = await inspect();
  assert.ok(expiredAfter.state.player.magazines.rpg < expiredBefore.state.player.magazines.rpg || expiredAfter.reloading);
  await save('ammo-expired-consumption.json', { expiredBefore, expiredAfter });
  await browser.wait(stateCondition('!scene.isWeaponReloading()'), 'reload before supply');
  const supplyCore = await targetDown('supply');
  const beforeEmptying = await inspect();
  for (let deployedCount = 0; (await inspect()).state.player.currentItemId !== null && deployedCount < 30; deployedCount++) {
    await browser.tap('KeyQ'); await sleep(90);
  }
  const supplyBefore = await inspect();
  assert.equal(supplyBefore.state.player.currentItemId, null);
  const supply = await collect('supply', supplyCore);
  assert.equal(supply.state.player.currentItemId, 'mine');
  assert.equal(supply.state.player.items.mine, 2);
  assert.equal(supply.state.frenzy.phase, 'boss');
  await park(640, 430); await browser.tap('KeyQ');
  const deployed = await inspect();
  assert.equal(deployed.state.player.items.mine, 1);
  assert.ok(deployed.props.some(prop => prop.id === 'mine'));
  await save('supply-empty-slot-deployed.json', { beforeEmptying, supplyBefore, supply, deployed });
  await layout('boss-wide', 1920, 720); await layout('boss-narrow', 960, 720);
  const beforeBoss = await browser.evaluate('window.__FRENZY_FIXTURE__.report()');
  assert.equal(beforeBoss.bosses.length, 1);
  const boss = await browser.evaluate('window.__FRENZY_FIXTURE__.prepareBoss()');
  await browser.wait(stateCondition('!scene.isWeaponReloading()'), 'ready for boss');
  await browser.move('GameScene', boss.x, boss.y);
  await fireUntil("window.__GAME__.scene.isActive('FrenzyResultScene')", 'boss finished by real shot');
  await waitScene('FrenzyResultScene'); await browser.release();
  const won = await inspect();
  assert.equal(won.state.frenzy.phase, 'won');
  assert.equal(won.state.frenzy.ammoUntilMs, 0); assert.equal(won.state.frenzy.breachUntilMs, 0);
  const observed = await browser.evaluate('window.__FRENZY_FIXTURE__.report()');
  assert.equal(observed.bosses.length, 1);
  for (const title of ['弹药狂热', '破阵强化', '突击补给']) assert.equal(observed.records.filter(entry => entry.name === 'pickup' && entry.data.title.startsWith(title)).length, 1);
  assert.deepEqual(await saves(), baseline);
  await save('won.json', { snapshot: won, observed, texts: await browser.texts('FrenzyResultScene'), save: await saves() });
  await browser.screenshot('won');
  results.push({ name: 'production-frenzy-controlled-chain', passed: true, natural: false, recordEligible: false });
  await browser.tap('Enter'); await waitScene('GameScene');
  const fresh = await inspect();
  assert.equal(fresh.state.frenzy.presetId, 'explosive');
  assert.deepEqual(fresh.state.frenzy.targets, { ammo: 'alive', breach: 'alive', supply: 'alive' });
  assert.equal(fresh.state.frenzy.ammoUntilMs, 0); assert.equal(fresh.state.frenzy.breachUntilMs, 0);
  assert.equal(fresh.state.stats.kills, 0);
  assert.equal(fresh.state.player.currentItemId, initial.state.player.currentItemId);
  assert.deepEqual(fresh.state.player.items, initial.state.player.items);
  await save('won-retry-fresh.json', fresh);
  await browser.evaluate("(() => { const run = window.__GAME__.scene.getScene('GameScene').getState().frenzy; run.recordEligible = false; run.elapsedMs = 299000; })()");
  await waitScene('FrenzyResultScene');
  const timeout = await inspect();
  assert.equal(timeout.state.frenzy.phase, 'timeout');
  assert.equal(timeout.state.frenzy.elapsedMs, 300000);
  assert.deepEqual(await saves(), baseline);
  await save('timeout.json', { snapshot: timeout, texts: await browser.texts('FrenzyResultScene'), fixture: '公开计时器压缩至299000ms，最后一秒真实运行至300000ms；非自然生存五分钟。' });
  await browser.screenshot('timeout');
  await browser.clickText('FrenzyResultScene', '同预设再来一局'); await waitScene('GameScene');
  const timeoutRetry = await inspect();
  assert.equal(timeoutRetry.state.frenzy.presetId, 'explosive');
  assert.equal(timeoutRetry.state.stats.kills, 0);
  assert.deepEqual(timeoutRetry.state.frenzy.targets, { ammo: 'alive', breach: 'alive', supply: 'alive' });
  await save('timeout-retry-fresh.json', timeoutRetry);
  results.push({ name: 'timeout-and-retry', passed: true, fixtureTimer: true });
  assert.equal(browser.errors.length, 0); assert.equal(browser.failures.length, 0);
  await save('result.json', { passed: true, results, excluded: ['自然三核心通关', '正式成功纪录', '无侧栏在当前布局不可达', '真人手感'] });
} catch (error) {
  process.exitCode = 1;
  await save('failure.json', { message: error.message, stack: error.stack, results, snapshot: await inspect().catch(() => null), fixture: await browser.evaluate('window.__FRENZY_FIXTURE__?.report()').catch(() => null), errors: browser.errors, failedRequests: browser.failures });
  await browser.screenshot('failure').catch(() => {});
  console.error(error);
} finally { await session.close(); }
